"""Export every in-game sprite as an SVG string into app/js/sprites.js.

Usage: python3 export_sprites.py <output sprites.js>
Each sprite has a size (w, h) and an anchor (ax, ay): the point inside the sprite that sits on the
game position (feet for characters, center for icons, bottom-left for the fridge).
"""
import json, sys
from base import *
from chars import *
from props import *
import icons as IC

SPR = {}


def add(name, content, box):
    minx, miny, w, h = box
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
           f'viewBox="{minx} {miny} {w} {h}">{content}</svg>')
    SPR[name] = {"w": w, "h": h, "ax": -minx, "ay": -miny, "svg": svg}


KID = (-110, -278, 220, 300)
ADULT = (-125, -335, 250, 357)
ICON = (-62, -62, 124, 124)

# raiders and pajama variants (hands free: carried snacks float above the head in game)
DINO = {"": None, "_lava": ("#FF6B5E", "#D9433A", "#FFD3C9"), "_ice": ("#7FD4FF", "#3FA3D9", "#DDF3FF"),
        "_gold": ("#FFC93C", "#D69E12", "#FFF0B8")}
STAR = {"": None, "_midnight": ("#2B3A8F", "#7FB4FF", "#FFF6E5"), "_sunset": ("#FF7EB6", "#FFA630", "#FFF6E5")}
for suf, col in DINO.items():
    add("kid_dino" + suf, kid_dino(with_cookie=False, colors=col), KID)
for suf, col in STAR.items():
    add("kid_star" + suf, kid_star(with_juice=False, colors=col), KID)

# family, pets, machines
add("dad", dad(), ADULT)
add("dad_awake", dad(awake=True), ADULT)
add("mom", mom(), ADULT)
add("mom_asleep", mom(asleep=True), ADULT)
add("mika", mika(), ADULT)
add("baby", baby(), (-70, -198, 140, 215))
add("baby_asleep", baby("asleep"), (-70, -198, 140, 215))
add("baby_cry", baby("cry"), (-70, -198, 140, 215))
add("biscuit", biscuit_sit(), (-72, -202, 144, 220))
add("biscuit_sleep", biscuit_sleep(), (-105, -100, 210, 118))
add("dusty", dusty(), (-90, -66, 180, 86))
add("dusty_angry", dusty("angry"), (-90, -66, 180, 86))

# props
add("fridge", fridge_open(0, 0, 240, 300, is_open=False), (-10, -310, 350, 356))
add("fridge_open", fridge_open(0, 0, 240, 300), (-10, -310, 350, 356))
add("jar", jar(0, 0), (-50, -124, 100, 130))
add("microwave", microwave(0, 0, 170, 96, display=""), (-6, -102, 182, 108))
for nm, col in (("red", RED), ("yellow", "#FFC93C"), ("blue", MOON), ("green", GREEN)):
    add("brick_" + nm, brick(0, 0, col), (-28, -37, 56, 50))

# snack and gadget icons
SNACK_IDS = ["juice", "cookie", "chips", "soda", "chocolate", "pizza", "jelly", "popcorn", "cereal",
             "icecream", "cake", "watermelon", "carrot", "donut"]
for sid, (_, _, fn) in zip(SNACK_IDS, IC.SNACKS):
    add("snack_" + sid, fn(), ICON)
GAD_IDS = ["socks", "slippers", "oil", "muffler", "cape", "box", "biscuits", "decoy", "laser", "clicker",
           "toot", "rccar", "goggles", "radar", "dummy", "pacifier", "musicbox", "claw", "drone"]
for gid, (_, _, fn) in zip(GAD_IDS, IC.GADGETS):
    add("gad_" + gid, fn(), ICON)

# extra items and UI icons
add("snack_popbag", rrect(-30, -40, 60, 80, 8, "#F3E3C3") + rrect(-30, -12, 60, 24, 0, RED, stroke="none")
    + line(-30, -12, 30, -12, sw=4) + line(-30, 12, 30, 12, sw=4)
    + text(0, 8, "POP", 22, fill="white", weight=700), ICON)
add("ui_coin", circ(0, 0, 44, "#FFC93C") + circ(0, 0, 32, "#FFE08A", sw=4) + star(0, 2, 20, "#FFC93C", sw=4), ICON)
add("ui_wrapper", poly([(-56, -22), (-30, 0), (-56, 22)], "#FFC93C") + poly([(56, -22), (30, 0), (56, 22)], "#FFC93C")
    + ell(0, 0, 36, 26, GLOW) + path("M -18 -10 Q 0 -22 18 -10", "none", stroke="white", sw=5)
    + IC.sparkle(34, -34, 12), ICON)
add("ui_star", star(0, 4, 54, "#FFC93C", sw=6), ICON)
add("ui_star_off", star(0, 4, 54, "#2B2F77", sw=6), ICON)
add("ui_card", g(rrect(-34, -48, 68, 96, 10, MILK) + rrect(-24, -38, 48, 40, 6, PINK, sw=4)
                 + text(0, -8, "?!", 30, fill=NAVY, weight=700) + line(-22, 16, 22, 16, sw=4)
                 + line(-22, 30, 12, 30, sw=4), 0, 0, 1.0, rot=-8), ICON)
add("ui_lock", path("M -20 -8 L -20 -26 Q -20 -50 0 -50 Q 20 -50 20 -26 L 20 -8", "none", sw=10)
    + rrect(-34, -10, 68, 58, 12, "#8E9AAF") + circ(0, 16, 8, NAVY, stroke="none")
    + line(0, 16, 0, 32, sw=6), ICON)
add("ui_lunchbox", rrect(-48, -26, 96, 66, 12, RED) + rrect(-48, -26, 96, 22, 12, "#C93B32")
    + path("M -18 -26 Q -18 -48 0 -48 Q 18 -48 18 -26", "none", sw=8) + rrect(-9, -10, 18, 14, 4, GLOW, sw=4), ICON)

out = sys.argv[1] if len(sys.argv) > 1 else "sprites.js"
with open(out, "w") as f:
    f.write("// Generated by art/src/export_sprites.py. Do not edit by hand.\n")
    f.write("export const SPRITES = " + json.dumps(SPR, separators=(",", ":")) + ";\n")
print(len(SPR), "sprites,", sum(len(v["svg"]) for v in SPR.values()) // 1024, "KB")
