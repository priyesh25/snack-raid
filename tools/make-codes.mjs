// Builds app/js/codes.js from the plain list below. The app only ships hashes, so the codes are not
// readable in the game's source. The readable list lives in docs/codes.md.
// Run: node tools/make-codes.mjs
import { writeFileSync } from 'node:fs';

const PROMO = {
  SNACKRAID: 'coins500', COOKIEJAR: 'coins1000', MIDNIGHT: 'cards3', GOLDENDONUT: 'wrap5',
  LAVADINO: 'pj_dino_lava', GOLDENPJS: 'pj_dino_gold', STARLIGHT: 'pj_star_midnight',
  TOYCHEST: 'gad_goggles', SQUEAK: 'gad_decoy', BUNNYHOP: 'gad_slippers',
  BIGPOCKETS: 'pouch', GADGETBELT: 'slot3', DOUBLECOINS: 'double10', LEVELUP: 'levelup',
  LUNCHBOX: 'lunchbox', BOSSKEY: 'bosskey',
};
const CHEAT = {
  OPENSESAME: 'unlockall', PIGGYBANK: 'coins5000', SLEEPYHEADS: 'sleepy', NINJAFEET: 'ninja', SLOWCLOCK: 'slowclock',
  XRAYEYES: 'xray', DEEPPOCKETS: 'deeppockets', GHOSTMODE: 'ghost', EASYSNACKS: 'easysnacks', GADGETGALORE: 'gadgetgalore',
};
const fnv = s => { let h = 0x811c9dc5; for (const ch of s) { h ^= ch.charCodeAt(0); h = Math.imul(h, 0x01000193) >>> 0; } return h.toString(16).padStart(8, '0'); };
const table = {};
for (const [k, v] of Object.entries(PROMO)) table[fnv(k)] = ['promo', v];
for (const [k, v] of Object.entries(CHEAT)) table[fnv(k)] = ['cheat', v];
if (Object.keys(table).length !== Object.keys(PROMO).length + Object.keys(CHEAT).length) throw new Error('hash collision');

const src = `// Generated by tools/make-codes.mjs. Do not edit by hand.
// Promo codes and cheat codes. Only hashes ship with the game. The readable list is in docs/codes.md.
import { save, persist, openBox, giveGadget } from './save.js';
import { GADGETS, PAJAMAS } from './data.js';

const TABLE = ${JSON.stringify(table)};
const fnv = s => { let h = 0x811c9dc5; for (const ch of s) { h ^= ch.charCodeAt(0); h = Math.imul(h, 0x01000193) >>> 0; } return h.toString(16).padStart(8, '0'); };

// what each cheat does, for the toggle list
export const CHEATS = {
  sleepy: ['Sleepy Heads', 'Every sleeper gets 2 extra Zs'],
  ninja: ['Ninja Feet', 'Every step is one ring size quieter'],
  slowclock: ['Slow Clock', 'The night lasts twice as long'],
  xray: ['X-Ray Eyes', 'Creaky boards and the Secret Stash always show'],
  deeppockets: ['Deep Pockets', 'Carry 5 snacks'],
  ghost: ['Ghost Mode', 'Nobody can see you'],
  easysnacks: ['Easy Snacks', 'No melting, fizzing, wobbling, crumbs or crinkles'],
  gadgetgalore: ['Gadget Galore', 'Gadgets never run out'],
};

const PROMOS = {
  coins500: () => { save.coins += 500; return '500 coins'; },
  coins1000: () => { save.coins += 1000; return '1,000 coins'; },
  cards3: () => { save.cards = Math.min(9, save.cards + 3); return '3 Excuse Cards'; },
  wrap5: () => { save.wrappers += 5; return '5 Golden Wrappers'; },
  pouch: () => { save.bonusPouch = true; return 'Hoodie Pouch: carry 3 snacks'; },
  slot3: () => { save.bonusSlot = true; return 'A third gadget slot'; },
  double10: () => { save.doubleNights += 10; return 'Double coins for your next 10 nights'; },
  levelup: () => { let n = 0; for (const id of Object.keys(save.gadgets)) if (save.gadgets[id] < 5) { save.gadgets[id]++; n++; } return n ? n + ' gadgets went up a level' : 'No gadgets to level up yet. Try again later'; },
  lunchbox: () => { const b = openBox('Lunchbox'); return 'A Lunchbox: ' + b.coins + ' coins and an Excuse Card'; },
  bosskey: () => { save.bossKey = true; return 'The Boss night is open'; },
};

export function redeem(text) {
  const code = String(text || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
  if (!code) return { ok: false, msg: 'Type a code first.' };
  const hit = TABLE[fnv(code)];
  if (!hit) return { ok: false, msg: 'That code does not work.' };
  const [kind, id] = hit;
  if (kind === 'promo') {
    if (save.promos.includes(id)) return { ok: false, msg: 'You already used that code.' };
    let got;
    if (id.startsWith('pj_')) { const pid = id.slice(3), pj = PAJAMAS.find(p => p.id === pid); if (!save.pajamas.includes(pid)) save.pajamas.push(pid); save.pajama = pid; got = pj.name + ' pajamas'; }
    else if (id.startsWith('gad_')) { const gid = id.slice(4); if (save.gadgets[gid]) { save.coins += GADGETS[gid].price; got = 'You already own the ' + GADGETS[gid].name + ', so here are ' + GADGETS[gid].price + ' coins'; } else { giveGadget(gid); got = GADGETS[gid].name; } }
    else { got = PROMOS[id](); if (id === 'levelup' && got.startsWith('No gadgets')) return { ok: false, msg: got + '.' }; }
    save.promos.push(id); persist();
    return { ok: true, kind, title: 'Promo unlocked!', msg: got + '.' };
  }
  // cheats
  if (id === 'unlockall') { save.unlockAll = true; persist(); return { ok: true, kind, title: 'Cheat on!', msg: 'Every night is unlocked.' }; }
  if (id === 'coins5000') { save.coins += 5000; persist(); return { ok: true, kind, title: 'Cha-ching!', msg: '5,000 coins. You can use this one again.' }; }
  if (!save.cheatsFound.includes(id)) save.cheatsFound.push(id);
  save.cheats[id] = !save.cheats[id]; persist();
  return { ok: true, kind, title: 'Cheat ' + (save.cheats[id] ? 'ON' : 'OFF'), msg: CHEATS[id][0] + ': ' + CHEATS[id][1] + '.' };
}
`;
writeFileSync(new URL('../app/js/codes.js', import.meta.url), src);
console.log('wrote app/js/codes.js with', Object.keys(table).length, 'codes');
